#!/usr/bin/env python3
"""Derive the setup-file word-kind tables for the runtime ROM loader (Phase D).

The compiled-in setup files (assets/obseg/setup/*.c, generated by Getools) are
NOT the ROM bytes: words the generator wrapped in _mkword()/_mkshort() come out
byte-identical to the N64 image (the PC arm of those macros swaps the halves
back), words it emitted as plain literals come out as native u32 (a full byte
swap of the ROM word), and prop.c then patches the handful of u16/u8 fields the
generator emitted as literals at load time.  A runtime converter therefore
needs, for every propdef / intro record type, the KIND of each word:

    K32  native u32 / f32 / offset    - host bytes = ROM bytes reversed
    K16  two u16 fields               - each half reversed
    K8   four bytes                   - host bytes = ROM bytes

Rather than transcribe ~45 struct layouts by hand (a silent field shift is a
week), this script DERIVES the tables from data: for every setup, the ROM
file (inflated) and the compiled object's .data (build_win/asset_obj/*.o.raw,
the pre-objcopy object, read with objdump/nm) are walked in lockstep, record
by record, and each (type, word) position keeps the set of kinds consistent
with every instance in every file.  A position with NO consistent kind is a
port edit or a walker bug and is reported; a position that stays ambiguous
(every instance symmetric - typically 0) is resolved to K32 and listed.

The fixed-layout sections (pads, boundpads, waypoints, waygroups, paths,
ailist table, name tables, path arrays, AI streams) are VERIFIED against the
kinds the runtime converter hard-codes for them, so a generator drift there
shows up here too.

Output: port/generated/setup_kinds.h (committed; regenerate after a build):

    python3 scripts/port/gen_setup_kinds.py [build_win]
"""
import csv
import os
import re
import struct
import subprocess
import sys
import zlib

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
BUILD = os.path.join(ROOT, sys.argv[1] if len(sys.argv) > 1 else "build_win")
ROM = os.path.join(ROOT, "baserom.u.z64")
CSV = os.path.join(ROOT, "scripts", "filelist.u.csv")
OUT = os.path.join(ROOT, "port", "generated", "setup_kinds.h")
OBJD = "i686-w64-mingw32-objdump"
NM = "i686-w64-mingw32-nm"

# sizepropdef (src/game/loadobjectmodel.c) in words; the sizeof() entries were
# measured against bondtypes.h (Guard 28, Door 256, DoorScale 8, Object 128,
# TintedGlass 148, Key 132 bytes)
PROPDEF_SIZES = {
    9: 7, 1: 64, 2: 2, 3: 32, 42: 32, 47: 37, 43: 32, 36: 32, 4: 33, 5: 32, 6: 0x3b, 7: 0x21,
    8: 0x22, 10: 0x40, 11: 0x95, 12: 32, 13: 0x36, 14: 3, 17: 32, 18: 3, 19: 4, 44: 5,
    20: 0x2d, 21: 0x22, 22: 4, 37: 10, 23: 4, 24: 1, 25: 2, 26: 2, 27: 2, 28: 2, 29: 2,
    30: 4, 31: 1, 32: 4, 33: 5, 34: 1, 35: 4, 38: 4, 39: 0x2c, 40: 0x2d, 45: 0x38, 46: 7,
}
PROPDEF_END = 48
PROPDEF_NAMES = ("NOTHING DOOR DOOR_SCALE PROP KEY ALARM CCTV MAGAZINE COLLECTABLE GUARD MONITOR "
                 "MULTI_MONITOR RACK AUTOGUN LINK DEBRIS UNK16 HAT GUARD_ATTRIBUTE SWITCH AMMO ARMOUR TAG "
                 "OBJECTIVE_START OBJECTIVE_END OBJECTIVE_DESTROY_OBJECT OBJECTIVE_COMPLETE_CONDITION "
                 "OBJECTIVE_FAIL_CONDITION OBJECTIVE_COLLECT_OBJECT OBJECTIVE_DEPOSIT_OBJECT "
                 "OBJECTIVE_PHOTOGRAPH OBJECTIVE_NULL OBJECTIVE_ENTER_ROOM OBJECTIVE_DEPOSIT_OBJECT_IN_ROOM "
                 "OBJECTIVE_COPY_ITEM WATCH_MENU_OBJECTIVE_TEXT GAS_RELEASING RENAME LOCK_DOOR VEHICHLE "
                 "AIRCRAFT UNK41 GLASS SAFE SAFE_ITEM TANK CAMERAPOS TINTED_GLASS END").split()
# portMeasureIntro (prop.c) in words: sizeof(struct SetupIntro*)/4
INTRO_SIZES = {0: 3, 1: 4, 2: 4, 3: 8, 4: 2, 5: 2, 6: 10, 7: 3, 8: 2}
INTRO_END = 9
INTRO_NAMES = "SPAWN ITEM AMMO SWIRL ANIM CUFF CAMERA WATCH CREDITS END".split()

K32, K16, K8, KSK, KKS = 1, 2, 3, 4, 5
KNAME = {K32: "K32", K16: "K16", K8: "K8", KSK: "KSK", KKS: "KKS"}
# K16 = both halves are u16 (each reversed); K8 = four bytes; KSK = first half a
# u16, second half two bytes ({u16 scale; u8 hidden; u8 type} - every propdef
# header); KKS = two bytes then a u16


def wslpath(p):
    if len(p) > 2 and p[1] == ":":
        return "/mnt/" + p[0].lower() + p[2:].replace(chr(92), "/")
    return p


def run(cmd):
    try:
        return subprocess.check_output(cmd, text=True, stderr=subprocess.DEVNULL)
    except (OSError, subprocess.CalledProcessError):
        return subprocess.check_output(["wsl"] + [wslpath(c) for c in cmd], text=True)


def section_bytes(obj, sec):
    out = run([OBJD, "-s", "-j", sec, obj])
    data = bytearray()
    for line in out.splitlines():
        m = re.match(r"\s([0-9a-f]+) ((?:[0-9a-f]{2,8} ?){1,4})\s", line)
        if not m:
            continue
        off = int(m.group(1), 16)
        hexs = m.group(2).replace(" ", "")
        if off != len(data):
            data.extend(b"\0" * (off - len(data)))
        data.extend(bytes.fromhex(hexs))
    return bytes(data)


def symbols(obj):
    syms = {}
    for line in run([NM, "-n", obj]).splitlines():
        m = re.match(r"([0-9a-f]+) ([dDrR]) _?(\w+)", line)
        if m:
            syms[m.group(3)] = (int(m.group(1), 16), m.group(2).lower())
    return syms


def relocs(obj):
    """.data offset -> target section name ('.data' / '.rdata')"""
    r = {}
    insec = None
    for line in run([OBJD, "-r", obj]).splitlines():
        m = re.match(r"RELOCATION RECORDS FOR \[(\S+)\]", line)
        if m:
            insec = m.group(1)
            continue
        m = re.match(r"([0-9a-f]+)\s+dir32\s+(\S+)", line)
        if m and insec == ".data":
            r[int(m.group(1), 16)] = m.group(2)
    return r


def be32(b, o):
    return struct.unpack_from(">I", b, o)[0]


def kinds_of(romword, hostword):
    s = set()
    if hostword == romword[::-1]:
        s.add(K32)
    if hostword == romword[1::-1] + romword[3:1:-1]:
        s.add(K16)
    if hostword == romword:
        s.add(K8)
    if hostword == romword[1::-1] + romword[2:4]:
        s.add(KSK)
    if hostword == romword[0:2] + romword[3:1:-1]:
        s.add(KKS)
    return s


class Table:
    def __init__(self, names, sizes):
        self.names = names
        self.sizes = sizes
        self.sets = {}     # (type, word) -> set of kinds still consistent
        self.seen = {}     # (type, word) -> instances
        self.bad = []      # (file, section, type, index, word, rombytes, hostbytes)

    def feed(self, fname, section, rtype, index, romwords, hostwords):
        for w, (rw, hw) in enumerate(zip(romwords, hostwords)):
            key = (rtype, w)
            ks = kinds_of(rw, hw)
            if key not in self.sets:
                self.sets[key] = set(ks)
                self.seen[key] = 0
            else:
                self.sets[key] &= ks
            self.seen[key] += 1
            if not self.sets[key]:
                self.bad.append((fname, section, rtype, index, w, rw.hex(), hw.hex()))
                self.sets[key] = set(ks)  # keep classifying the rest


def walk_records(fname, section, rom, romoff, host, hostoff, sizes, endtype, table, typeof):
    """walk both images in lockstep; returns (count, romend, hostend)"""
    n = 0
    while True:
        rw0 = rom[romoff:romoff + 4]
        hw0 = host[hostoff:hostoff + 4]
        rtype = typeof(rw0)
        htype = typeof(hw0)
        if rtype != htype:
            # the ROM is the truth; a compiled header whose type byte sits
            # elsewhere is a generator bug (word 0 will be reported below)
            print("TYPE MISMATCH: %s %s record %d: ROM type %d, compiled type %d at rom+0x%x / host+0x%x (walking by the ROM type)"
                  % (fname, section, n, rtype, htype, romoff, hostoff))
        size = sizes.get(rtype, 1)
        romwords = [rom[romoff + i * 4:romoff + i * 4 + 4] for i in range(size)]
        hostwords = [host[hostoff + i * 4:hostoff + i * 4 + 4] for i in range(size)]
        table.feed(fname, section, rtype, n, romwords, hostwords)
        n += 1
        romoff += size * 4
        hostoff += size * 4
        if rtype == endtype:
            return n, romoff, hostoff


def check_fixed(fname, what, rom, romoff, host, hostoff, nwords, expect, report):
    """verify a fixed-kind run of words; expect = list of kinds (None = pointer word)"""
    for w in range(nwords):
        rw = rom[romoff + w * 4:romoff + w * 4 + 4]
        hw = host[hostoff + w * 4:hostoff + w * 4 + 4]
        k = expect[w % len(expect)]
        if k is None:
            continue
        if k not in kinds_of(rw, hw):
            report.append("%s %s word %d: rom %s host %s not %s" % (fname, what, w, rw.hex(), hw.hex(), KNAME[k]))


def main():
    rombytes = open(ROM, "rb").read()
    rows = {}
    for r in csv.reader(open(CSV, newline="")):
        if len(r) >= 3 and "/obseg/setup/" in r[2]:
            base = r[2].split("/")[-1]
            if base.endswith(".bin"):
                base = base[:-4]
            rows[base] = (int(r[0]), int(r[1]))
    names = sorted(rows)
    propdefs = Table(PROPDEF_NAMES, PROPDEF_SIZES)
    intro = Table(INTRO_NAMES, INTRO_SIZES)
    fixed_report = []
    stats = []

    for name in names:
        obj = os.path.join(BUILD, "asset_obj", name + ".o.raw")
        if not os.path.exists(obj):
            print("skip %s: no %s" % (name, obj))
            continue
        ofs, size = rows[name]
        d = rombytes[ofs:ofs + size]
        rom = zlib.decompress(d[2:], -15) if d[:2] == b"\x11\x72" else d
        host = section_bytes(obj, ".data")
        rdata = section_bytes(obj, ".rdata")
        syms = symbols(obj)
        rel = relocs(obj)

        # header: 10 offsets (ROM) / 10 pointers (host); ROM section offsets
        hdr = [be32(rom, i * 4) for i in range(10)]
        r_wp, r_wg, r_intro, r_pd, r_paths, r_ai, r_pads, r_bpads, r_pn, r_bpn = hdr
        h = {k: syms[k][0] for k in ("pathwaypoints", "pathsets", "intro", "propDefs", "patrolpaths",
                                       "ailists", "padlist", "pad3dlist") if k in syms}
        h_pn = syms["padnames"][0] if "padnames" in syms else None
        h_bpn = syms["pad3dnames"][0] if "pad3dnames" in syms else None

        # propDefs + intro: the typed walks
        npd, _, _ = walk_records(name, "propDefs", rom, r_pd, host, h["propDefs"], PROPDEF_SIZES, PROPDEF_END,
                                 propdefs, lambda w: w[3])
        nin, _, _ = walk_records(name, "intro", rom, r_intro, host, h["intro"], INTRO_SIZES, INTRO_END,
                                 intro, lambda w: w[3])

        # pads: 9 f32 + plink(ptr) + stan(0)   (44 B); terminated by plink == 0
        npads = 0
        o = r_pads
        while be32(rom, o + 36) != 0:
            check_fixed(name, "pad %d" % npads, rom, o, host, h["padlist"] + npads * 44, 9, [K32], fixed_report)
            # the name: ROM offset -> string in the file; host: reloc into .rdata
            so = be32(rom, o + 36)
            rs = rom[so:rom.index(b"\0", so)]
            ho = h["padlist"] + npads * 44 + 36
            hs = rdata[struct.unpack_from("<I", host, ho)[0]:]
            hs = hs[:hs.index(b"\0")]
            if rel.get(ho) != ".rdata" or rs != hs:
                fixed_report.append("%s pad %d name: rom %r host %r (%s)" % (name, npads, rs, hs, rel.get(ho)))
            npads += 1
            o += 44
        # boundpads: 9 f32 + plink + stan + 6 f32 (68 B)
        nb = 0
        o = r_bpads
        while be32(rom, o + 36) != 0:
            hb = h["pad3dlist"] + nb * 68
            check_fixed(name, "boundpad %d" % nb, rom, o, host, hb, 9, [K32], fixed_report)
            check_fixed(name, "boundpad %d bbox" % nb, rom, o + 44, host, hb + 44, 6, [K32], fixed_report)
            nb += 1
            o += 68
        # waypoints: padID, neighbours(ptr), groupNum, dist; terminated by padID < 0
        nw = 0
        o = r_wp
        while struct.unpack_from(">i", rom, o)[0] >= 0:
            hw = h["pathwaypoints"] + nw * 16
            check_fixed(name, "waypoint %d" % nw, rom, o, host, hw, 4, [K32, None, K32, K32], fixed_report)
            if rel.get(hw + 4) != ".data":
                fixed_report.append("%s waypoint %d neighbours: no .data reloc" % (name, nw))
            else:  # the neighbour list itself: s32 ... -1
                ro = be32(rom, o + 4)
                ho = struct.unpack_from("<I", host, hw + 4)[0]
                k = 0
                while True:
                    check_fixed(name, "waypoint %d neighbours[%d]" % (nw, k), rom, ro + k * 4, host, ho + k * 4, 1, [K32], fixed_report)
                    if struct.unpack_from(">i", rom, ro + k * 4)[0] < 0:
                        break
                    k += 1
            nw += 1
            o += 16
        # waygroups: neighbours(ptr), waypoints(ptr), dist; terminated by neighbours == 0
        ng = 0
        o = r_wg
        while be32(rom, o) != 0:
            hg = h["pathsets"] + ng * 12
            check_fixed(name, "waygroup %d" % ng, rom, o, host, hg, 3, [None, None, K32], fixed_report)
            for fld in (0, 4):
                ro = be32(rom, o + fld)
                ho = struct.unpack_from("<I", host, hg + fld)[0]
                k = 0
                while True:
                    check_fixed(name, "waygroup %d list@%d[%d]" % (ng, fld, k), rom, ro + k * 4, host, ho + k * 4, 1, [K32], fixed_report)
                    if struct.unpack_from(">i", rom, ro + k * 4)[0] < 0:
                        break
                    k += 1
            ng += 1
            o += 12
        # patrol paths: waypoints(ptr), {u8 id, u8 isLoop, u16 len}; terminated by waypoints == 0
        npth = 0
        o = r_paths
        while be32(rom, o) != 0:
            hp = h["patrolpaths"] + npth * 8
            rw = rom[o + 4:o + 8]
            hw = host[hp + 4:hp + 8]
            if not (rw[0] == hw[0] and rw[1] == hw[1] and rw[2:4] == hw[3:1:-1]):
                fixed_report.append("%s path %d word1: rom %s host %s (expected id,isLoop bytes + swapped len)" % (name, npth, rw.hex(), hw.hex()))
            ro = be32(rom, o)
            ho = struct.unpack_from("<I", host, hp)[0]
            k = 0
            while True:
                check_fixed(name, "path %d wp[%d]" % (npth, k), rom, ro + k * 4, host, ho + k * 4, 1, [K32], fixed_report)
                if struct.unpack_from(">i", rom, ro + k * 4)[0] < 0:
                    break
                k += 1
            npth += 1
            o += 8
        # ailists: ailist(ptr), id; terminated by ailist == 0; the streams are bytes
        nai = 0
        aidiff = 0
        o = r_ai
        while be32(rom, o) != 0:
            ha = h["ailists"] + nai * 8
            check_fixed(name, "ailist %d" % nai, rom, o, host, ha, 2, [None, K32], fixed_report)
            ro = be32(rom, o)
            ho = struct.unpack_from("<I", host, ha)[0]
            # compare the byte streams up to the compiled symbol's end (next symbol)
            nxt = min([v[0] for v in syms.values() if v[0] > ho] + [len(host)])
            n = nxt - ho
            if rom[ro:ro + n] != host[ho:ho + n]:
                aidiff += 1
            nai += 1
            o += 8
        # name tables: ptr ... 0
        for what, ro0, ho0 in (("padnames", r_pn, h_pn), ("boundpadnames", r_bpn, h_bpn)):
            if ro0 == 0 or ho0 is None:
                continue
            k = 0
            while be32(rom, ro0 + k * 4) != 0:
                so = be32(rom, ro0 + k * 4)
                rs = rom[so:rom.index(b"\0", so)]
                hp = ho0 + k * 4
                hs = rdata[struct.unpack_from("<I", host, hp)[0]:]
                hs = hs[:hs.index(b"\0")]
                if rel.get(hp) != ".rdata" or rs != hs:
                    fixed_report.append("%s %s[%d]: rom %r host %r" % (name, what, k, rs, hs))
                k += 1
        stats.append((name, len(rom), npd, nin, npads, nb, nw, ng, npth, nai, aidiff))

    # ---- report
    print("%-18s %7s %5s %5s %5s %4s %4s %4s %4s %4s %s" % ("setup", "bytes", "pdefs", "intro", "pads", "bpad", "wp", "wg", "path", "ai", "ai-streams-differing"))
    for s in stats:
        print("%-18s %7d %5d %5d %5d %4d %4d %4d %4d %4d %d" % s)
    print()
    problems = 0
    for t, label in ((propdefs, "propdef"), (intro, "intro")):
        for b in t.bad:
            print("NO KIND FITS: %s %s type %s(%d) rec %d word %d rom %s host %s" % (b[0], b[1], t.names[b[2]] if b[2] < len(t.names) else "?", b[2], b[3], b[4], b[5], b[6]))
            problems += 1
    for line in fixed_report:
        print("FIXED-SECTION MISMATCH: " + line)
        problems += 1

    # ---- tables
    def table(t, sizes, count, label):
        lines = []
        ambiguous = []
        for ty in range(count):
            size = sizes.get(ty, 1)
            kinds = []
            for w in range(size):
                s = t.sets.get((ty, w))
                if s is None:
                    kinds.append(K32)   # never seen in retail data
                    ambiguous.append("%s w%d unseen" % (t.names[ty], w))
                elif len(s) == 1:
                    kinds.append(next(iter(s)))
                elif not s:
                    kinds.append(K32)   # no kind fit an instance: reported above, K32 here
                    ambiguous.append("%s w%d NO FIT (see report)" % (t.names[ty], w))
                else:
                    # symmetric values only (typically 0 everywhere): prefer K32, then
                    # the halfword kinds, then the byte kind - listed below either way
                    kinds.append(next(k for k in (K32, K16, KSK, KKS, K8) if k in s))
                    ambiguous.append("%s w%d %s (%d seen)" % (t.names[ty], w, "/".join(KNAME[k] for k in sorted(s)), t.seen[(ty, w)]))
            lines.append("    /* %2d %-32s */ { %3d, { %s } }," % (ty, t.names[ty], size, ", ".join(str(k) for k in kinds)))
        return lines, ambiguous

    pd_lines, pd_amb = table(propdefs, PROPDEF_SIZES, PROPDEF_END + 1, "propdef")
    in_lines, in_amb = table(intro, INTRO_SIZES, INTRO_END + 1, "intro")
    maxpd = max(PROPDEF_SIZES.values())
    maxin = max(INTRO_SIZES.values())
    with open(OUT, "w", newline="\n") as f:
        f.write("/* GENERATED by scripts/port/gen_setup_kinds.py - do not edit.\n"
                " * Word kinds for the runtime setup-file converter (port/src/romdata.c, Phase D):\n"
                " * derived from the compiled-in setups vs the ROM files, every retail setup\n"
                " * (%d files). 1 = K32 (native u32/f32/offset: bytes reversed), 2 = K16 (two u16:\n"
                " * halves reversed), 3 = K8 (bytes as in ROM). Positions never seen non-symmetric\n"
                " * in retail data default to K32 (listed below). */\n" % len(stats))
        f.write("#define SETUP_KIND_K32 1\n#define SETUP_KIND_K16 2\n#define SETUP_KIND_K8 3\n"
                "#define SETUP_KIND_KSK 4 /* u16 then two bytes */\n#define SETUP_KIND_KKS 5 /* two bytes then u16 */\n")
        f.write("#define SETUP_PROPDEF_TYPES %d\n#define SETUP_PROPDEF_MAXWORDS %d\n" % (PROPDEF_END + 1, maxpd))
        f.write("#define SETUP_INTRO_TYPES %d\n#define SETUP_INTRO_MAXWORDS %d\n" % (INTRO_END + 1, maxin))
        f.write("struct setupkinds { u16 words; u8 kind[%d]; };\n" % max(maxpd, maxin))
        f.write("static const struct setupkinds kSetupPropdefKinds[SETUP_PROPDEF_TYPES] = {\n" + "\n".join(pd_lines) + "\n};\n")
        f.write("static const struct setupkinds kSetupIntroKinds[SETUP_INTRO_TYPES] = {\n" + "\n".join(in_lines) + "\n};\n")
        f.write("/* ambiguous / unseen positions (resolved to K32):\n")
        for a in pd_amb + in_amb:
            f.write(" *   %s\n" % a)
        f.write(" */\n")
    print("wrote %s; %d propdef + %d intro ambiguous positions; %d problems" % (OUT, len(pd_amb), len(in_amb), problems))
    sys.exit(1 if problems else 0)


if __name__ == "__main__":
    main()
